// Карта зависимостей киберимплантов.
// Ключ — название ОПЦИИ, значение — массив БАЗ, которые должны быть установлены.
// Опции без записи в карте — свободные (ставятся сами по себе).

// Нормализация: ё→е, lowercase, trim. Чтобы "Разъём" и "Разъем" считались одним.
const norm = (s) => String(s || '').toLowerCase().replace(/ё/g, 'е').trim();

/** Установлена ли база (по нечёткому совпадению подстроки). */
function isInstalled(req, selected) {
    const reqNorm = norm(req);
    return selected.some(name => {
        const n = norm(name);
        return n === reqNorm || n.includes(reqNorm);
    });
}

/** Возвращает список баз для опции или пустой массив. */
export function getRequirements(optionName) {
    return cyberwareRequirements[optionName] || [];
}

/** Проверяет, все ли базы установлены. */
export function areRequirementsMet(optionName, selectedList) {
    const reqs = getRequirements(optionName);
    if (reqs.length === 0) return true;
    return reqs.every(r => isInstalled(r, selectedList));
}

