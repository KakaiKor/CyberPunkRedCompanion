    static renderRumor(rumor) {
        const container = document.getElementById('rumorResult');
        if (!container) return;

        let truthClass = "";
        if (rumor.truthLevel.includes("правда")) truthClass = "truth-true";
        else if (rumor.truthLevel.includes("полуправда")) truthClass = "truth-half";
        else truthClass = "truth-false";

        const html = `
            <div class="rumor-card">
                <div class="rumor-header">
                    <span class="rumor-type">${this.translateType(rumor.type)}</span>
                    <span class="rumor-truth ${truthClass}">🎭 ${rumor.truthLevel}</span>
                </div>
                <div class="rumor-text">📢 «${this.escapeHtml(rumor.text)}»</div>
                <div class="rumor-hook">
                    <i class="fas fa-hook"></i> <strong>Сюжетный крючок:</strong> ${this.escapeHtml(rumor.hook)}
                </div>
            </div>
        `;
        container.innerHTML = html;
    }

    static translateType(type) {
        const map = {
            crime: "🕵️ Криминал",
            corporate: "🏢 Корпорации",
            legend: "📜 Легенды улиц",
            tech: "🔧 Технологии",
            gang: "💀 Банды",
            danger: "⚠️ Опасности"
        };
        return map[type] || type;
    }

    static copyToClipboard() {
        const container = document.getElementById('rumorResult');
        if (!container || !container.innerText) return;
        const text = container.innerText;
        navigator.clipboard.writeText(text).then(() => alert('Слух скопирован в буфер обмена!'));
    }

    static escapeHtml(str) {
        if (!str) return '';
        return str.replace(/[&<>]/g, function(m) {
            if (m === '&') return '&amp;';
            if (m === '<') return '&lt;';
            if (m === '>') return '&gt;';
            return m;
        });
    }
